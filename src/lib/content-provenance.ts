// ─── Utility Functions ──────────────────────────────────────────────────────────

/** Returns the ordered list of provenance levels for UI selectors */
export const PROVENANCE_ORDER: ProvenanceLevel[] = [
  'genuine',
  'ai_assisted',
  'ai_enhanced',
  'ai_generated',
];

/** Get the display config for a given provenance level */
export function getProvenanceTier(level: ProvenanceLevel) {
  return PROVENANCE_TIERS[level] ?? PROVENANCE_TIERS.genuine;
}

/** Check if a provenance level requires digital_replica_consent */
export function requiresReplicantConsent(level: ProvenanceLevel): boolean {
  return level === 'ai_generated';
}

/** Build a ProvenanceMetadata object for a new content upload */
export function createProvenanceMetadata(
  level: ProvenanceLevel,
  creatorName?: string,
  consentTimestamp?: string | null,
  toolsUsed?: string[],
): ProvenanceMetadata {
  return {
    level,
    declaredBy: 'creator',
    creatorName,
    creatorConsent: consentTimestamp ?? undefined,
    toolsUsed,
    declaredAt: new Date().toISOString(),
    autoDetectionResult: null,
  };
}

/**
 * Determines the suggested provenance level from auto-detection confidence.
 * - > 90% confidence → ai_generated
 * - 50–90% confidence → ai_assisted
 * - < 50% confidence → trust creator's self-declaration
 */
export function suggestProvenanceFromDetection(confidence: number): ProvenanceLevel | null {
  if (confidence > 90) return 'ai_generated';
  if (confidence >= 50) return 'ai_assisted';
  return null; // trust self-declaration
}

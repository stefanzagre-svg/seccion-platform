// ─── Content Provenance Classification ─────────────────────────────────────────
// Defines the 4-tier provenance taxonomy for SECCION platform transparency.
// Used by ProvenanceBadge, ProvenanceSelector, and auto-detection services.
// ────────────────────────────────────────────────────────────────────────────────

export type ProvenanceLevel =
  | 'genuine'       // 100% human-created
  | 'ai_assisted'   // Human-created with AI enhancement
  | 'ai_generated'  // Fully AI-generated (Replicant content)
  | 'ai_enhanced';  // Human original modified with AI tools

export interface ProvenanceMetadata {
  level: ProvenanceLevel;
  declaredBy: 'creator' | 'platform_auto' | 'admin';
  creatorName?: string;
  creatorConsent?: string;   // ISO timestamp of digital_replica_consent
  toolsUsed?: string[];      // e.g., ['midjourney', 'runway', 'seccion-replicant']
  declaredAt: string;        // ISO timestamp
  autoDetectionResult?: AutoDetectionResult | null;
}

export interface AutoDetectionResult {
  isAiGenerated: boolean;
  confidence: number;        // 0–100
  detectedModel?: string;    // e.g., 'midjourney-v6', 'dall-e-3'
  suggestedLevel: ProvenanceLevel;
  source: 'hive' | 'c2pa' | 'synthid';
  checkedAt: string;         // ISO timestamp
}

